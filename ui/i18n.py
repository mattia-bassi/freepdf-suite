_language = "en"
_listeners: list[Callable[[], None]] = []


def current_language() -> str:
    """Return the active language code."""
    return _language


def tr(key: str) -> str:
    """Translate *key* for the active language (falls back to English, then key)."""
    table = _MESSAGES.get(_language) or _MESSAGES["en"]
    if key in table:
        return table[key]
    return _MESSAGES["en"].get(key, key)


def set_language(code: str) -> str:
    """Set the active language code without notifying listeners."""
    global _language
    if code not in _MESSAGES:
        code = "en"
    _language = code
    return _language


def register_retranslate(callback: Callable[[], None]) -> Callable[[], None]:
    """Register a callback invoked when the language changes; returns unregister."""

    _listeners.append(callback)

    def unregister() -> None:
        if callback in _listeners:
            _listeners.remove(callback)

    return unregister


def apply_language(code: str) -> str:
    """Switch language and refresh all registered UI callbacks."""
    resolved = set_language(code)
    for callback in list(_listeners):
        callback()
    return resolved


def init_language() -> str:
    """Load language from config and set it before the UI is built."""
    from .config_loader import load_app_config

    code = str(load_app_config().get("language", "en"))
    return set_language(code)
